"""Generate Cloudflare Pages HTTP security headers from the final site HTML.

Run after prerender.py so the header CSP permits the exact executable inline
scripts in all published pages. GitHub Pages does not interpret _headers.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from security_policy import REFERRER_POLICY, build_content_security_policy
from site_config import PAGE_SLUGS

ROOT = Path(__file__).resolve().parents[1]
MAX_HEADER_LINE_LENGTH = 2000


def generate_headers(root: Path = ROOT) -> str:
    """Return one deterministic Cloudflare rule for the complete public site."""
    html = '\n'.join(
        (root / f'{slug}.html').read_text(encoding='utf-8')
        for slug in PAGE_SLUGS
    )
    policy = build_content_security_policy(
        html, include_frame_ancestors=True, upgrade_insecure_requests=True,
    )
    headers = (
        '# Generated by scripts/generate_security_headers.py after prerender.py.\n'
        '# Cloudflare Pages reads this file; GitHub Pages does not apply it.\n'
        '/*\n'
        f'  Content-Security-Policy: {policy}\n'
        '  X-Content-Type-Options: nosniff\n'
        '  X-Frame-Options: DENY\n'
        f'  Referrer-Policy: {REFERRER_POLICY}\n'
        '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()\n'
        '  Strict-Transport-Security: max-age=31536000\n'
    )
    if any(len(line) > MAX_HEADER_LINE_LENGTH for line in headers.splitlines()):
        raise ValueError('Generated _headers exceeds the Cloudflare Pages 2000-character line limit')
    return headers


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT, help='Directory containing the final ten HTML pages.')
    parser.add_argument('--output', type=Path, help='Output file; defaults to <root>/_headers.')
    arguments = parser.parse_args()
    root = arguments.root.resolve()
    output = arguments.output or root / '_headers'
    try:
        headers = generate_headers(root)
        output.write_text(headers, encoding='utf-8', newline='\n')
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(f'Generated HTTP security headers for {len(PAGE_SLUGS)} pages in {output}')


if __name__ == '__main__':
    main()
